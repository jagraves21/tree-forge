from functools import cache

import pytest

from tic_tac_toe import BOARD_SIZE, GameState, Move, Player, TicTacToeGame
from tic_tac_toe.canonicalizer import TicTacToeCanonicalizer


ALL_CELLS = [
	(row, column)
	for row in range(BOARD_SIZE)
	for column in range(BOARD_SIZE)
]

# An arrangement without any symmetry: its orbit has all eight members.
ASYMMETRIC_ROWS = ("XO.", ".X.", "..O")

# Unchanged by reflection across the main diagonal, so its orbit has four.
DIAGONALLY_SYMMETRIC_ROWS = ("X.O", ".X.", "O..")


def rotate(cell: tuple[int, int]) -> tuple[int, int]:
	"""Rotate a cell a quarter turn."""
	row, column = cell

	return column, BOARD_SIZE - 1 - row


def reflect(cell: tuple[int, int]) -> tuple[int, int]:
	"""Mirror a cell left to right."""
	row, column = cell

	return row, BOARD_SIZE - 1 - column


def dihedral_group() -> set[tuple[tuple[int, int], ...]]:
	"""Generate the eight board symmetries as cell permutations.

	Each permutation lists, for every cell in row-major order, the cell
	it maps to. They are generated by closing rotate() and reflect()
	under composition, independently of the canonicalizer.
	"""
	identity = tuple(ALL_CELLS)
	group = {identity}
	pending = [identity]

	while pending:
		current = pending.pop()

		for generator in (rotate, reflect):
			composed = tuple(generator(cell) for cell in current)

			if composed not in group:
				group.add(composed)
				pending.append(composed)

	return group


def permutation_of(transform) -> tuple[tuple[int, int], ...]:
	return tuple(
		(moved.row, moved.column)
		for moved in (transform(Move(row, column)) for row, column in ALL_CELLS)
	)


def apply_transform(state: GameState, transform) -> GameState:
	"""Move every piece of a state according to a move transformation."""
	board = [[None] * BOARD_SIZE for _ in range(BOARD_SIZE)]

	for row, column in ALL_CELLS:
		moved = transform(Move(row, column))
		board[moved.row][moved.column] = state.board[row][column]

	return GameState(board=board, current_player=state.current_player)


def encode_position(position: str) -> int:
	"""Independently encode a position string as a base-three integer."""
	values = {".": 0, "X": 1, "O": 2}
	result = 0

	for symbol in position:
		result = result * 3 + values[symbol]

	return result


@cache
def reachable_states() -> tuple[GameState, ...]:
	"""Every position reachable in a game, found without the canonicalizer."""
	game = TicTacToeGame()
	seen: dict[tuple, GameState] = {}
	pending = [game.initial_state()]

	while pending:
		state = pending.pop()
		identity = (
			state.current_player,
			tuple(tuple(row) for row in state.board),
		)

		if identity in seen:
			continue

		seen[identity] = state

		for move in game.legal_moves(state):
			child = GameState(
				board=[row.copy() for row in state.board],
				current_player=state.current_player,
			)
			game.make_move(child, move)
			pending.append(child)

	return tuple(seen.values())


