class TestCanonicalize:
	def test_key_matches_the_canonical_position_key(
		self,
		canonicalizer: TicTacToeCanonicalizer,
		make_state,
	) -> None:
		state = make_state(*ASYMMETRIC_ROWS)

		assert canonicalizer.canonicalize(state).key == (
			canonicalizer.canonical_position_key(state)
		)

	def test_to_canonical_move_produces_the_canonical_board(
		self,
		canonicalizer: TicTacToeCanonicalizer,
		make_state,
	) -> None:
		state = make_state(*ASYMMETRIC_ROWS)
		position = canonicalizer.canonicalize(state)

		canonical_state = apply_transform(state, position.to_canonical_move)

		assert canonicalizer.position_key(canonical_state) == position.key

	def test_moves_round_trip_through_both_transformations(
		self,
		canonicalizer: TicTacToeCanonicalizer,
		make_state,
	) -> None:
		position = canonicalizer.canonicalize(make_state(*ASYMMETRIC_ROWS))

		for row, column in ALL_CELLS:
			move = Move(row, column)
			canonical_move = position.to_canonical_move(move)

			assert position.from_canonical_move(canonical_move) == move

	def test_canonical_moves_stay_on_the_board(
		self,
		canonicalizer: TicTacToeCanonicalizer,
		make_state,
	) -> None:
		position = canonicalizer.canonicalize(make_state(*ASYMMETRIC_ROWS))

		for row, column in ALL_CELLS:
			canonical_move = position.to_canonical_move(Move(row, column))

			assert 0 <= canonical_move.row < BOARD_SIZE
			assert 0 <= canonical_move.column < BOARD_SIZE

	def test_legal_moves_map_onto_the_canonical_boards_empty_cells(
		self,
		canonicalizer: TicTacToeCanonicalizer,
		game: TicTacToeGame,
		make_state,
	) -> None:
		state = make_state(*ASYMMETRIC_ROWS)
		position = canonicalizer.canonicalize(state)
		canonical_state = apply_transform(state, position.to_canonical_move)

		mapped = {
			position.to_canonical_move(move)
			for move in game.legal_moves(state)
		}

		assert mapped == set(game.legal_moves(canonical_state))

	def test_symmetric_positions_share_a_key(
		self,
		canonicalizer: TicTacToeCanonicalizer,
		make_state,
	) -> None:
		state = make_state(*ASYMMETRIC_ROWS)
		expected = canonicalizer.canonicalize(state).key

		for _, transform in canonicalizer.iter_symmetries(state):
			symmetric = apply_transform(state, transform)

			assert canonicalizer.canonicalize(symmetric).key == expected

	def test_symmetric_positions_agree_on_the_canonical_move(
		self,
		canonicalizer: TicTacToeCanonicalizer,
		game: TicTacToeGame,
		make_state,
	) -> None:
		# Without symmetry in the position the canonical orientation is
		# unique, so a move and its image must have the same canonical move.
		state = make_state(*ASYMMETRIC_ROWS)
		original = canonicalizer.canonicalize(state)

		for _, transform in canonicalizer.iter_symmetries(state):
			symmetric = apply_transform(state, transform)
			canonical = canonicalizer.canonicalize(symmetric)

			for move in game.legal_moves(state):
				assert canonical.to_canonical_move(transform(move)) == (
					original.to_canonical_move(move)
				)

	def test_empty_board_round_trips_every_move(
		self,
		canonicalizer: TicTacToeCanonicalizer,
		game: TicTacToeGame,
	) -> None:
		position = canonicalizer.canonicalize(game.initial_state())

		for move in game.legal_moves(game.initial_state()):
			assert position.from_canonical_move(
				position.to_canonical_move(move)
			) == move

	@pytest.mark.parametrize("move", [
		Move(-1, -1),
		Move(3, 0),
		Move(0, 3),
		Move(5, 5),
	])
	def test_rejects_canonical_moves_outside_the_board(
		self,
		canonicalizer: TicTacToeCanonicalizer,
		game: TicTacToeGame,
		move: Move,
	) -> None:
		position = canonicalizer.canonicalize(game.initial_state())

		with pytest.raises(ValueError, match="Invalid canonical move"):
			position.from_canonical_move(move)
